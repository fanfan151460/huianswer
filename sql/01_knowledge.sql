-- 在 huianswer 数据库中执行；不包含数据库密码和 API key。
-- 向量与片段原文同表。4096 维先做精确检索，不创建 HNSW/IVFFlat 索引。
BEGIN;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS t_knowledge_base (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL CHECK (btrim(name) <> ''),
    description VARCHAR(1000) NOT NULL DEFAULT '',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
COMMENT ON TABLE t_knowledge_base IS '知识库：资料的逻辑集合';
-- description 的列注释由 07 迁移脚本统一设置，兼容已有库。
COMMENT ON COLUMN t_knowledge_base.deleted IS '0 正常，1 逻辑删除';

CREATE TABLE IF NOT EXISTS t_knowledge_document (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id BIGINT NOT NULL REFERENCES t_knowledge_base(id),
    doc_name VARCHAR(255) NOT NULL CHECK (btrim(doc_name) <> ''),
    file_path TEXT NOT NULL,
    metadata JSONB,
    status VARCHAR(16) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'running', 'success', 'failed')),
    enabled SMALLINT NOT NULL DEFAULT 0
        CONSTRAINT ck_knowledge_document_enabled CHECK (enabled IN (0, 1)),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    CONSTRAINT uk_document_id_kb UNIQUE (id, kb_id)
);
COMMENT ON TABLE t_knowledge_document IS '知识库中的原始文档及处理状态';
COMMENT ON COLUMN t_knowledge_document.file_path IS '原文件存储路径，不在本表保存文件二进制';
COMMENT ON COLUMN t_knowledge_document.metadata IS '可选元数据，JSON 对象';
COMMENT ON COLUMN t_knowledge_document.status IS 'pending 待处理，running 处理中，success 成功，failed 失败';
COMMENT ON COLUMN t_knowledge_document.enabled IS '0 启用，1 禁用；只控制检索，不改变解析状态或删除片段';
CREATE INDEX IF NOT EXISTS idx_document_kb_active
    ON t_knowledge_document (kb_id) WHERE deleted = 0;

CREATE TABLE IF NOT EXISTS t_knowledge_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kb_id BIGINT NOT NULL,
    doc_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL CHECK (btrim(content) <> ''),
    embedding vector(4096) NOT NULL,
    search_text TEXT,
    search_vector TSVECTOR GENERATED ALWAYS AS (
        to_tsvector('simple', coalesce(search_text, ''))
    ) STORED,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    -- 保证片段的 kb_id 与它所属文档一致，避免误写进其他知识库。
    CONSTRAINT fk_chunk_document FOREIGN KEY (doc_id, kb_id)
        REFERENCES t_knowledge_document (id, kb_id),
    CONSTRAINT uk_chunk_document_index UNIQUE (doc_id, chunk_index)
);
COMMENT ON TABLE t_knowledge_chunk IS '文档片段：原文、归属和嵌入向量';
COMMENT ON COLUMN t_knowledge_chunk.chunk_index IS '在文档中的序号，从 0 开始';
COMMENT ON COLUMN t_knowledge_chunk.embedding IS '4096 维嵌入；问题和文档必须使用同一嵌入模型配置';
COMMENT ON COLUMN t_knowledge_chunk.search_text IS 'HanLP 分词后的文本，空格分隔，保留词序和重复词';
COMMENT ON COLUMN t_knowledge_chunk.search_vector IS '基于 search_text 自动生成的全文检索向量，Java 不直接写入';
COMMENT ON COLUMN t_knowledge_chunk.deleted IS '通用逻辑删除标识；删除文档时按 doc_id 物理清理片段';
CREATE INDEX IF NOT EXISTS idx_chunk_kb_active
    ON t_knowledge_chunk (kb_id) WHERE deleted = 0;
CREATE INDEX IF NOT EXISTS idx_chunk_search_vector
    ON t_knowledge_chunk USING GIN (search_vector);
-- uk_chunk_document_index 的左前缀 doc_id 同时用于按文档清理，不重复加索引。
COMMIT;
