-- 在 huianswer 数据库中执行；先执行已有的 01、02、03 建表脚本。
-- 会话归属由登录上下文中的 userId 确定；本文件不创建外键。
-- 现有账号表 t_admin.name 对应 Java userName，已有 uk_admin_name 唯一约束。
BEGIN;

CREATE TABLE IF NOT EXISTS t_chat_conversation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(128) NOT NULL DEFAULT '新对话' CHECK (btrim(title) <> ''),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
COMMENT ON TABLE t_chat_conversation IS '用户会话：按用户归属，不绑定知识库';
COMMENT ON COLUMN t_chat_conversation.user_id IS '会话所属用户 ID，由后端登录上下文填写';
COMMENT ON COLUMN t_chat_conversation.title IS '会话标题，可截取首个问题生成';
COMMENT ON COLUMN t_chat_conversation.update_time IS '会话更新时间；新增消息时由业务同步更新';
COMMENT ON COLUMN t_chat_conversation.deleted IS '0 正常，1 逻辑删除';

CREATE INDEX IF NOT EXISTS idx_conversation_user_active
    ON t_chat_conversation (user_id, update_time DESC) WHERE deleted = 0;

CREATE TABLE IF NOT EXISTS t_chat_message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    turn_no INTEGER NOT NULL CHECK (turn_no > 0),
    role VARCHAR(16) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'success' CHECK (status IN ('success', 'failed')),
    sources JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(sources) = 'array'),
    model VARCHAR(128),
    total_tokens INTEGER CHECK (total_tokens >= 0),
    finish_reason VARCHAR(32),
    error_message TEXT,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1)),
    CONSTRAINT uk_message_conversation_turn_role UNIQUE (conversation_id, turn_no, role)
);
COMMENT ON TABLE t_chat_message IS '会话消息：用户问题和模型回答分别保存一行';
COMMENT ON COLUMN t_chat_message.conversation_id IS '所属会话 ID，业务必须校验会话属于当前用户且未删除';
COMMENT ON COLUMN t_chat_message.turn_no IS '问答轮次，从 1 开始；同一轮 user 与 assistant 共用编号';
COMMENT ON COLUMN t_chat_message.role IS 'user 用户问题，assistant 模型回答；系统提示词不作为聊天记录保存';
COMMENT ON COLUMN t_chat_message.content IS '正文；失败回答允许为空或保存已经生成的部分';
COMMENT ON COLUMN t_chat_message.status IS '只记录结束态：success 完整成功，failed 失败或中断';
COMMENT ON COLUMN t_chat_message.sources IS '本轮引用列表，元素包含 num、docId、docName、chunkId';
COMMENT ON COLUMN t_chat_message.model IS '生成本条回答的模型；用户消息为空';
COMMENT ON COLUMN t_chat_message.total_tokens IS '模型返回的本次调用总 token 数；尚未取得时为空';
COMMENT ON COLUMN t_chat_message.finish_reason IS '模型返回的结束原因，例如 stop、length；未取得时为空';
COMMENT ON COLUMN t_chat_message.error_message IS '失败时的简短原因，不保存密钥或第三方完整错误响应';
COMMENT ON COLUMN t_chat_message.deleted IS '0 正常，1 逻辑删除';

-- 上面的唯一约束以 conversation_id 为左前缀，也支持按会话查询消息。
-- 查询上下文时按轮次排序，每轮先 user 后 assistant，仅选完整成功的问答。
COMMIT;
