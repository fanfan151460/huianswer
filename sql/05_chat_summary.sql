-- 在 huianswer 数据库中执行；先执行 04_chat_memory.sql。
-- 每个会话只保留一份有效摘要；原始消息仍保存在 t_chat_message 中。
-- 会话归属由业务校验，本文件不创建外键。
BEGIN;

CREATE TABLE IF NOT EXISTS t_chat_summary (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    summary_until_turn_no INTEGER NOT NULL DEFAULT 0 CHECK (summary_until_turn_no >= 0),
    content TEXT NOT NULL DEFAULT '',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted SMALLINT NOT NULL DEFAULT 0 CHECK (deleted IN (0, 1))
);
COMMENT ON TABLE t_chat_summary IS '会话摘要：旧摘要与新增历史合并后覆盖更新，不删除原始消息';
COMMENT ON COLUMN t_chat_summary.conversation_id IS '所属会话 ID，业务校验会话存在、未删除且归属于当前用户';
COMMENT ON COLUMN t_chat_summary.user_id IS '所属用户 ID，由后端登录上下文填写';
COMMENT ON COLUMN t_chat_summary.summary_until_turn_no IS '摘要已覆盖到的问答轮次；0 表示尚未压缩，仅将完整成功的问答纳入摘要';
COMMENT ON COLUMN t_chat_summary.content IS '历史摘要正文，用于上下文理解，不作为当前知识库事实依据';
COMMENT ON COLUMN t_chat_summary.create_time IS '首次保存摘要的时间';
COMMENT ON COLUMN t_chat_summary.update_time IS '更新摘要内容和覆盖轮次时由业务同步更新';
COMMENT ON COLUMN t_chat_summary.deleted IS '0 正常，1 逻辑删除';

-- 仅约束未删除记录：每个会话最多一份有效摘要，逻辑删除后可重新创建。
CREATE UNIQUE INDEX IF NOT EXISTS uk_chat_summary_conversation_active
    ON t_chat_summary (conversation_id) WHERE deleted = 0;

COMMIT;
